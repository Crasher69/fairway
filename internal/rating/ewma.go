// Package rating — самообучающийся рейтинг прокси по каждому домену.
//
// Смысл всей затеи: один и тот же прокси может быть быстрым для одного сайта
// и полумёртвым (или забаненным) для другого, поэтому статистика копится не
// на прокси, а на ПАРУ (домен, прокси).
package rating

// EWMA — экспоненциальное скользящее среднее.
//
// Выбрано вместо окна из N последних значений сознательно: занимает O(1)
// памяти на пару (домен, прокси), само «забывает» старое и не требует
// чистки. Alpha — вес свежего замера: чем больше, тем быстрее реакция на
// изменения и тем сильнее шум.
type EWMA struct {
	alpha float64
	value float64
	count int
}

// NewEWMA создаёт среднее с заданным весом свежего замера (0 < alpha <= 1).
func NewEWMA(alpha float64) EWMA {
	if alpha <= 0 || alpha > 1 {
		alpha = defaultAlpha
	}
	return EWMA{alpha: alpha}
}

// Add добавляет замер. Первое значение принимается как есть — иначе среднее
// пришлось бы долго «разгонять» от нуля, и первые запросы врали бы в плюс.
func (e *EWMA) Add(v float64) {
	if e.alpha == 0 {
		e.alpha = defaultAlpha
	}
	if e.count == 0 {
		e.value = v
	} else {
		e.value += e.alpha * (v - e.value)
	}
	e.count++
}

// Value — текущее среднее. Ноль, если замеров ещё не было.
func (e *EWMA) Value() float64 { return e.value }

// Count — сколько замеров учтено. Нужен для холодного старта: пока замеров
// мало, прокси нельзя судить по среднему.
func (e *EWMA) Count() int { return e.count }
